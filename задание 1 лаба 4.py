import json # Импортируем библиотеку для работы с форматом json
def task() -> float: #Создаем функцию task, которая будет возвращать вещественные значения
    with open('input.json', 'r',
              encoding='utf-8') as file:  # Открываем файл input.json в режиме чтения ('r') с кодировкой UTF-8
        data = json.load(file)  # Загружаем данные из файла в переменную data
    #  Проверяем, является ли data словарем (dict). Если да — превращаем его в список
    if isinstance(data, dict):  # проверяем тип переменной
        data = [data]  # Превращаем словарь в список, содержащий один элемент
    # Считаем сумму произведений score * weight для всех элементов
    # Используем генератор списка: для каждого элемента (item) в data:
    # - берём значение score и weight (если нет — используем 0)
    # - перемножаем их
    # - sum() складывает все полученные произведения
    total = sum(item.get('score', 0) * item.get('weight', 0) for item in data)
    # .get('ключ', значение по умолчанию)
    # Если ключа нет — возвращается значение по умолчанию (в нашем случае — 0)
    # Округляем результат до 3 знаков после запятой и возвращаем его
    return round(total, 3)  # round(число, количество_знаков) — округляет число
print(task()) # Выводим на экран
